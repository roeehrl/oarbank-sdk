// Post-build: lay out the deployable asset directory.
//
//   deploy/oarbank/...   the built site (the Worker matches assets by full URL path,
//                        and Astro's `base` does not nest dist/)
//   deploy/_headers      response headers, every rule scoped to /oarbank/
//
// The Worker serves deploy/ with html_handling "auto-trailing-slash" and
// not_found_handling "404-page" (so misses under /oarbank/ get oarbank/404.html).
import { cpSync, mkdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { BASE, CSP, MAX_DEPLOY_FILES, SECURITY_HEADERS } from '../site.config.mjs';
import { DEPLOY_DIR, DIST_DIR, rel, walk } from './lib/fs.mjs';

const IMMUTABLE = 'Cache-Control: public, max-age=31536000, immutable';

export const HEADERS = `# Generated by site/scripts/assemble.mjs. Every rule is scoped to ${BASE}/.
${BASE}/*
  Content-Security-Policy: ${CSP}
${SECURITY_HEADERS.map((h) => `  ${h}`).join('\n')}

${BASE}/_astro/*
  ${IMMUTABLE}

${BASE}/_inline/*
  ${IMMUTABLE}

${BASE}/*.md
  X-Robots-Tag: noindex
  Content-Type: text/markdown; charset=utf-8

${BASE}/*.txt
  Content-Type: text/plain; charset=utf-8

${BASE}/schemas/*
  Access-Control-Allow-Origin: *

${BASE}/vectors/*
  Access-Control-Allow-Origin: *
`;

rmSync(DEPLOY_DIR, { recursive: true, force: true });
const target = join(DEPLOY_DIR, ...BASE.split('/').filter(Boolean));
mkdirSync(target, { recursive: true });
cpSync(DIST_DIR, target, { recursive: true });
writeFileSync(join(DEPLOY_DIR, '_headers'), HEADERS);

// File count per top-level folder: the Workers limit is per deployed version.
const assets = walk(target);
const byDir = new Map();
let bytes = 0;
for (const f of assets) {
  const top = rel(target, f).split('/');
  const key = top.length > 1 ? `${top[0]}/` : top[0].endsWith('.md') ? '*.md' : top[0].endsWith('.html') ? '*.html' : 'other';
  byDir.set(key, (byDir.get(key) ?? 0) + 1);
  bytes += statSync(f).size;
}
const breakdown = [...byDir].sort((a, b) => b[1] - a[1]).map(([k, n]) => `${k} ${n}`).join(', ');
console.log(`assemble: ${assets.length} files, ${(bytes / 1024).toFixed(0)} KiB in deploy${BASE}/ plus _headers (limit ${MAX_DEPLOY_FILES})`);
console.log(`assemble: ${breakdown}`);
if (assets.length > MAX_DEPLOY_FILES) {
  console.error(`assemble: ${assets.length} files exceeds the ${MAX_DEPLOY_FILES}-file limit`);
  process.exit(1);
}
